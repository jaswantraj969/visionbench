#!/bin/sh
# Generate the CPU lock files for Linux (the Docker image and CI) inside the pinned Python image:
#
#   docker run --rm -v "<clean export of the repo>:/src:ro" -v "<out dir>:/out" \
#     python:3.11-slim@sha256:<digest from the Dockerfile> sh /src/scripts/lock_cpu_linux.sh
#
# Writes /out/lock-cpu-linux.txt (runtime) and /out/lock-dev-cpu-linux.txt (runtime + dev tools).
# torch/torchvision are the CPU builds from the official PyTorch index; versions match the
# CUDA development lock (requirements/lock-dev-cu130.txt) without the +cu130 suffix.
set -eu
TORCH="torch==2.14.1+cpu torchvision==0.29.1+cpu"
INDEX="https://download.pytorch.org/whl/cpu"
python -m venv /tmp/venv
. /tmp/venv/bin/activate
python -m pip install --no-cache-dir -q --upgrade pip
python -m pip install --no-cache-dir -q $TORCH --index-url "$INDEX"
cp -r /src /tmp/src
python -m pip install --no-cache-dir -q /tmp/src --extra-index-url "$INDEX"
header() {
  echo "# CPU lock file for Linux ($1). Generated by scripts/lock_cpu_linux.sh on $(date -u +%Y-%m-%d)"
  echo "# in $(python -c 'import platform; print("Python", platform.python_version(), platform.system(), platform.machine())')."
  echo "# Install: python -m pip install -r <this file> --extra-index-url $INDEX"
  echo "#          python -m pip install --no-deps .   (or -e \".[dev]\" --no-deps for development)"
}
{ header runtime; python -m pip freeze --exclude visionbench; } > /out/lock-cpu-linux.txt
python -m pip install --no-cache-dir -q "/tmp/src[dev]" --extra-index-url "$INDEX"
{ header "runtime + dev tools"; python -m pip freeze --exclude visionbench; } > /out/lock-dev-cpu-linux.txt
echo "torch: $(python -c 'import torch; print(torch.__version__, torch.cuda.is_available())')"
wc -l /out/lock-cpu-linux.txt /out/lock-dev-cpu-linux.txt
