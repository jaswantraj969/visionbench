// Regenerate src/api/schema.d.ts from the FastAPI OpenAPI schema (the backend is the source of
// truth). `--check` regenerates into memory and fails if the committed file is stale (CI).
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..", "..");
const out = join(here, "..", "src", "api", "schema.d.ts");
const winPython = join(root, ".venv", "Scripts", "python.exe");
const posixPython = join(root, ".venv", "bin", "python");
const python =
  process.env.VISIONBENCH_PYTHON ??
  (existsSync(winPython) ? winPython : existsSync(posixPython) ? posixPython : "python");

const json = execFileSync(
  python,
  [
    "-c",
    "import json; from visionbench.api.main import create_app; " +
      "print(json.dumps(create_app().openapi(), sort_keys=True))",
  ],
  { cwd: root, encoding: "utf-8", maxBuffer: 64 * 1024 * 1024 },
);
const ast = await openapiTS(JSON.parse(json));
const banner =
  "// Generated by scripts/gen-api.mjs from the FastAPI OpenAPI schema. Do not edit.\n" +
  "// Regenerate with `npm run gen:api`; CI runs `npm run check:api`.\n";
const text = banner + astToString(ast);

if (process.argv.includes("--check")) {
  const current = existsSync(out) ? readFileSync(out, "utf-8") : "";
  if (current !== text) {
    console.error("src/api/schema.d.ts is stale: run `npm run gen:api` and commit the result");
    process.exit(1);
  }
  console.log("src/api/schema.d.ts is up to date");
} else {
  writeFileSync(out, text, "utf-8");
  console.log(`wrote ${out}`);
}
